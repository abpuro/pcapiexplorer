function slug(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function scenario(input: ScenarioInput): Scenario {
  return {
    ...input,
    id: input.id ?? slug(`${input.category}-${input.subcategory ?? "general"}-${input.title}`),
    tags: input.tags ?? [input.category, input.subcategory ?? "", input.title].filter(Boolean),
  };
}

